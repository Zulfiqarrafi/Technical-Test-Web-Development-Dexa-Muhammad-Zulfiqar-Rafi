-- ============================================================================
-- DEXA GROUP - SISTEM PRESENSI WFH & MONITORING KARYAWAN
-- Database Schema : Oracle Database 19c / 21c XE
-- ============================================================================

CREATE TABLE departments (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR2(20) NOT NULL,
  name VARCHAR2(100) NOT NULL,
  description VARCHAR2(255),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uq_departments_code UNIQUE (code)
);

CREATE TABLE employees (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nik VARCHAR2(30) NOT NULL,
  full_name VARCHAR2(120) NOT NULL,
  email VARCHAR2(120) NOT NULL,
  password_hash VARCHAR2(255) NOT NULL,
  phone VARCHAR2(25),
  position VARCHAR2(100) NOT NULL,
  department_id NUMBER NOT NULL,
  role VARCHAR2(20) DEFAULT 'EMPLOYEE' NOT NULL,
  work_location VARCHAR2(200),
  join_date VARCHAR2(10) NOT NULL,
  is_active NUMBER(1) DEFAULT 1 NOT NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uq_employees_nik UNIQUE (nik),
  CONSTRAINT uq_employees_email UNIQUE (email),
  CONSTRAINT chk_employees_role CHECK (role IN ('EMPLOYEE', 'HRD')),
  CONSTRAINT fk_employees_department FOREIGN KEY (department_id)
    REFERENCES departments (id)
);

CREATE INDEX idx_employees_department ON employees (department_id);
CREATE INDEX idx_employees_active ON employees (is_active);

CREATE TABLE attendances (
  id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  employee_id NUMBER NOT NULL,
  attendance_date VARCHAR2(10) NOT NULL,
  clock_in_time TIMESTAMP NOT NULL,
  clock_in_photo VARCHAR2(255) NOT NULL,
  clock_in_note CLOB,
  clock_in_ip VARCHAR2(60),
  clock_out_time TIMESTAMP,
  clock_out_photo VARCHAR2(255),
  clock_out_note CLOB,
  status VARCHAR2(20) DEFAULT 'ON_TIME' NOT NULL,
  work_duration_minutes NUMBER(10),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP NOT NULL,
  CONSTRAINT uq_attendances_emp_date UNIQUE (employee_id, attendance_date),
  CONSTRAINT chk_attendances_status CHECK (status IN ('ON_TIME', 'LATE')),
  CONSTRAINT fk_attendances_employee FOREIGN KEY (employee_id)
    REFERENCES employees (id) ON DELETE CASCADE
);

CREATE INDEX idx_attendances_date ON attendances (attendance_date);
CREATE INDEX idx_attendances_status ON attendances (status);

